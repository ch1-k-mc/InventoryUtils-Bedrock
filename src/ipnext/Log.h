#pragma once

#include <format>
#include <string>

namespace inventory_utils::ipnext::Log {

void write(int level, std::string const& message);
bool traceEnabled();
bool debugEnabled();

template <class... Args>
void trace(std::format_string<Args...> fmt, Args&&... args) {
    if (traceEnabled()) write(0, std::format(fmt, std::forward<Args>(args)...));
}
template <class... Args>
void debug(std::format_string<Args...> fmt, Args&&... args) {
    if (debugEnabled()) write(1, std::format(fmt, std::forward<Args>(args)...));
}
template <class... Args>
void info(std::format_string<Args...> fmt, Args&&... args) {
    write(2, std::format(fmt, std::forward<Args>(args)...));
}
template <class... Args>
void warn(std::format_string<Args...> fmt, Args&&... args) {
    write(3, std::format(fmt, std::forward<Args>(args)...));
}
template <class... Args>
void error(std::format_string<Args...> fmt, Args&&... args) {
    write(4, std::format(fmt, std::forward<Args>(args)...));
}

}
